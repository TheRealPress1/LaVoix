import AppKit
import Combine
import Foundation

enum NotchClipboardSettings {
    private static let enabledKey = "LaVoixNotchClipboardEnabled"

    /// Off until the user turns it on: it records what they copy.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: self.enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: self.enabledKey) }
    }
}

/// Everything you copied recently, kept on this Mac. Passwords copied from password managers are skipped.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    struct Entry: Identifiable, Codable, Equatable {
        enum Kind: String, Codable { case text, image, files }
        var id: UUID
        var kind: Kind
        var text: String?
        var paths: [String]?
        var date: Date
        var app: String?
    }

    /// Pasteboard types that clipboard managers agree not to record (https://nspasteboard.org).
    nonisolated static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ]

    static let maxEntries = 40
    static let maxTextLength = 20000

    @Published private(set) var entries: [Entry] = []
    @Published private(set) var copiedID: UUID?

    private let pasteboard: NSPasteboard
    private let directory: URL
    private var timer: Timer?
    private var lastChangeCount: Int
    private var thumbnails: [UUID: NSImage] = [:]

    init(pasteboard: NSPasteboard = .general, directory: URL? = nil) {
        self.pasteboard = pasteboard
        self.directory = directory ?? FileManager.default
            .urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("LaVoix/Clipboard", isDirectory: true)
        self.lastChangeCount = pasteboard.changeCount
        try? FileManager.default.createDirectory(at: self.directory, withIntermediateDirectories: true)
        self.load()
    }

    /// Sample data for debug rendering only.
    static func sample() -> ClipboardStore {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("lavoix-clip-sample-\(UUID().uuidString)")
        let store = ClipboardStore(pasteboard: NSPasteboard(name: NSPasteboard.Name("lavoix.sample")), directory: dir)
        let now = Date()
        store.entries = [
            Entry(id: UUID(), kind: .text, text: "https://github.com/TheRealPress1/LaVoix", paths: nil, date: now.addingTimeInterval(-20), app: "Dia"),
            Entry(id: UUID(), kind: .text, text: "Let's move the launch to the 14th and I'll send the revised plan tonight.", paths: nil, date: now.addingTimeInterval(-190), app: "Slack"),
            Entry(id: UUID(), kind: .files, text: nil, paths: ["/Users/me/Documents/Q3 plan.pdf"], date: now.addingTimeInterval(-900), app: "Finder"),
            Entry(id: UUID(), kind: .text, text: "swift build -c release && ./install.sh", paths: nil, date: now.addingTimeInterval(-4000), app: "Terminal"),
            Entry(id: UUID(), kind: .text, text: "+33 6 12 34 56 78", paths: nil, date: now.addingTimeInterval(-9000), app: "Contacts"),
        ]
        return store
    }

    // MARK: - Watching

    func start() {
        guard self.timer == nil else { return }
        self.lastChangeCount = self.pasteboard.changeCount
        // The pasteboard has no change notification; checking an integer twice a second is effectively free.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        self.timer?.invalidate()
        self.timer = nil
    }

    /// Checks the pasteboard once. Public so tests can drive it without waiting for the timer.
    func poll() {
        let count = self.pasteboard.changeCount
        guard count != self.lastChangeCount else { return }
        self.lastChangeCount = count
        self.capture()
    }

    private func capture() {
        let types = Set((self.pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = self.pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty
        {
            self.record(Entry(id: UUID(), kind: .files, text: nil, paths: urls.map(\.path), date: Date(), app: app))
        } else if let raw = self.pasteboard.string(forType: .string),
                  !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            self.record(Entry(id: UUID(), kind: .text, text: String(raw.prefix(Self.maxTextLength)), paths: nil, date: Date(), app: app))
        } else if let image = NSImage(pasteboard: self.pasteboard), let png = Self.pngData(image, maxSide: 1600) {
            let id = UUID()
            try? png.write(to: self.imageURL(id))
            self.record(Entry(id: id, kind: .image, text: nil, paths: nil, date: Date(), app: app))
        }
    }

    private func record(_ entry: Entry) {
        // Copying the same thing again moves it to the top instead of adding a duplicate.
        if let index = self.entries.firstIndex(where: { Self.sameContent($0, entry) }) {
            self.removeFiles(for: entry)
            var existing = self.entries.remove(at: index)
            existing.date = entry.date
            existing.app = entry.app
            self.entries.insert(existing, at: 0)
        } else {
            self.entries.insert(entry, at: 0)
        }
        while self.entries.count > Self.maxEntries { self.remove(self.entries[self.entries.count - 1]) }
        self.save()
    }

    private static func sameContent(_ a: Entry, _ b: Entry) -> Bool {
        a.kind == b.kind && a.text == b.text && a.paths == b.paths && a.kind != .image
    }

    // MARK: - Actions

    /// Puts an entry back on the clipboard.
    func copy(_ entry: Entry) {
        self.pasteboard.clearContents()
        switch entry.kind {
        case .text:
            self.pasteboard.setString(entry.text ?? "", forType: .string)
        case .files:
            let urls = (entry.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            self.pasteboard.writeObjects(urls)
        case .image:
            if let image = NSImage(contentsOf: self.imageURL(entry.id)) { self.pasteboard.writeObjects([image]) }
        }
        // Our own write is not a new copy; just float the entry to the top.
        self.lastChangeCount = self.pasteboard.changeCount
        if let index = self.entries.firstIndex(where: { $0.id == entry.id }), index != 0 {
            var moved = self.entries.remove(at: index)
            moved.date = Date()
            self.entries.insert(moved, at: 0)
            self.save()
        }
        self.copiedID = entry.id
        Task { [weak self] in
            try? await Task.sleep(nanoseconds: 1_200_000_000)
            if self?.copiedID == entry.id { self?.copiedID = nil }
        }
    }

    func remove(_ entry: Entry) {
        self.removeFiles(for: entry)
        self.entries.removeAll { $0.id == entry.id }
        self.save()
    }

    func clear() {
        for entry in self.entries { self.removeFiles(for: entry) }
        self.entries = []
        self.save()
    }

    // MARK: - Images

    func thumbnail(for entry: Entry) -> NSImage? {
        guard entry.kind == .image else { return nil }
        if let cached = self.thumbnails[entry.id] { return cached }
        guard let image = NSImage(contentsOf: self.imageURL(entry.id)) else { return nil }
        self.thumbnails[entry.id] = image
        return image
    }

    private func imageURL(_ id: UUID) -> URL { self.directory.appendingPathComponent("\(id.uuidString).png") }

    private func removeFiles(for entry: Entry) {
        guard entry.kind == .image else { return }
        self.thumbnails[entry.id] = nil
        try? FileManager.default.removeItem(at: self.imageURL(entry.id))
    }

    private static func pngData(_ image: NSImage, maxSide: CGFloat) -> Data? {
        guard let tiff = image.tiffRepresentation, var rep = NSBitmapImageRep(data: tiff) else { return nil }
        let longest = CGFloat(max(rep.pixelsWide, rep.pixelsHigh))
        if longest > maxSide, longest > 0 {
            let scale = maxSide / longest
            let size = NSSize(width: CGFloat(rep.pixelsWide) * scale, height: CGFloat(rep.pixelsHigh) * scale)
            let scaled = NSImage(size: size)
            scaled.lockFocus()
            image.draw(in: NSRect(origin: .zero, size: size))
            scaled.unlockFocus()
            if let t = scaled.tiffRepresentation, let r = NSBitmapImageRep(data: t) { rep = r }
        }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: - Saving

    private var indexURL: URL { self.directory.appendingPathComponent("history.json") }

    private func save() {
        guard let data = try? JSONEncoder().encode(self.entries) else { return }
        try? data.write(to: self.indexURL, options: [.atomic, .completeFileProtection])
    }

    private func load() {
        guard let data = try? Data(contentsOf: self.indexURL),
              let saved = try? JSONDecoder().decode([Entry].self, from: data) else { return }
        self.entries = saved.filter { $0.kind != .image || FileManager.default.fileExists(atPath: self.imageURL($0.id).path) }
    }
}
